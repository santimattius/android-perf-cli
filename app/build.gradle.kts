// ── BuildConfig codegen ────────────────────────────────────────────────────────
// Generates BuildConfig.kt with a compile-time VERSION constant sourced from
// project.version. The file is written to build/generated/buildconfig/ (already
// covered by the root .gitignore `build/` rule — no .gitignore change needed).
val generateBuildConfig by tasks.registering {
    val version = project.version.toString()
        .takeIf { it != "unspecified" } ?: "0.1.0"
    val outDir = layout.buildDirectory.dir("generated/buildconfig")
    outputs.dir(outDir)
    doLast {
        val dir = outDir.get().asFile.also { it.mkdirs() }
        File(dir, "BuildConfig.kt").writeText(
            """
            package dev.perf.cli

            /** Generated by generateBuildConfig — do not edit. */
            object BuildConfig {
                const val VERSION = "$version"
            }
            """.trimIndent()
        )
    }
}

sourceSets.main { kotlin.srcDir(layout.buildDirectory.dir("generated/buildconfig")) }
tasks.named("compileKotlin") { dependsOn(generateBuildConfig) }
